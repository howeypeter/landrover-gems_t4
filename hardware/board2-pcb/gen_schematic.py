"""Generate board2.kicad_sch (KiCad schematic) from the Board 2 design.

Source of truth for the design: docs/board2-pcb2-summary.md and diagrams/gems-2pcb-schematic.html Sheet 2.
Every pin gets a short net label at its connection point (no wires), so nets are defined purely by label names.
Run:  python gen_schematic.py   (writes board2.kicad_sch + board2.kicad_pro next to this file)
Footprints marked PLACEHOLDER are stock stand-ins to be replaced by custom/verified ones (see docs/board2-bom.md).
"""
import re, uuid, os, json

KICAD = r"C:\Program Files\KiCad\10.0\share\kicad"
HERE = os.path.dirname(os.path.abspath(__file__))
G = 2.54
ROOT = str(uuid.uuid4())
u = lambda: str(uuid.uuid4())

_libcache = {}
def lib_text(lib):
    if lib not in _libcache:
        with open(f"{KICAD}\\symbols\\{lib}.kicad_sym", encoding="utf-8") as f:
            _libcache[lib] = f.read()
    return _libcache[lib]

def extract_symbol(lib, name):
    t = lib_text(lib)
    i = t.index(f'\t(symbol "{name}"')
    d = 0
    for j in range(i, len(t)):
        if t[j] == "(":
            d += 1
        elif t[j] == ")":
            d -= 1
            if d == 0:
                return t[i:j + 1]
    raise SystemExit("unbalanced " + name)

def pins_of(block):
    out = {}
    for m in re.finditer(r'\(pin \w+ \w+\s*\(at ([-\d.]+) ([-\d.]+) (\d+)\)\s*\(length ([\d.]+)\)(?:(?!\(pin ).)*?\(number "([^"]+)"', block, re.S):
        out[m.group(5)] = (float(m.group(1)), float(m.group(2)), int(m.group(3)))
    return out

PARTS = {}   # lib_id -> (embedded text, pins)
def use(lib, name):
    lid = f"{lib}:{name}"
    if lid not in PARTS:
        blk = extract_symbol(lib, name)
        emb = blk.replace(f'(symbol "{name}"', f'(symbol "{lid}"', 1)
        PARTS[lid] = (emb, pins_of(blk))
    return lid

body = []
def place(lid, ref, value, footprint, x, y, nets, note=""):
    """nets: dict pin_number -> net name. Origin (x,y) in grid units (x2.54 mm)."""
    X, Y = x * G, y * G
    emb, pins = PARTS[lid]
    s = [f'\t(symbol (lib_id "{lid}") (at {X:.2f} {Y:.2f} 0) (unit 1) (exclude_from_sim no) (in_bom yes) (on_board yes) (dnp no) (uuid "{u()}")',
         f'\t\t(property "Reference" "{ref}" (at {X + 4:.2f} {Y - 2:.2f} 0) (effects (font (size 1.27 1.27)) (justify left)))',
         f'\t\t(property "Value" "{value}" (at {X + 4:.2f} {Y:.2f} 0) (effects (font (size 1.27 1.27)) (justify left)))',
         f'\t\t(property "Footprint" "{footprint}" (at {X:.2f} {Y:.2f} 0) (effects (font (size 1.27 1.27)) hide))',
         f'\t\t(property "Datasheet" "~" (at {X:.2f} {Y:.2f} 0) (effects (font (size 1.27 1.27)) hide))']
    if note:
        s.append(f'\t\t(property "Description" "{note}" (at {X:.2f} {Y:.2f} 0) (effects (font (size 1.27 1.27)) hide))')
    for pn in pins:
        s.append(f'\t\t(pin "{pn}" (uuid "{u()}"))')
    s.append(f'\t\t(instances (project "board2" (path "/{ROOT}" (reference "{ref}") (unit 1))))')
    s.append('\t)')
    body.append("\n".join(s))
    for pn, net in nets.items():
        px, py, ang = pins[pn]
        lx, ly = X + px, Y - py
        la = (ang + 180) % 360
        just = {0: "left", 180: "right", 90: "left", 270: "right"}[la]
        body.append(f'\t(label "{net}" (at {lx:.2f} {ly:.2f} {la}) (effects (font (size 1.27 1.27)) (justify {just} bottom)) (uuid "{u()}"))')

def text(msg, x, y, size=1.8):
    body.append(f'\t(text "{msg}" (at {x * G:.2f} {y * G:.2f} 0) (effects (font (size {size} {size})) (justify left bottom)) (uuid "{u()}"))')

C1x02 = use("Connector_Generic", "Conn_01x02")
C1x04 = use("Connector_Generic", "Conn_01x04")
C1x08 = use("Connector_Generic", "Conn_01x08")
C1x16 = use("Connector_Generic", "Conn_01x16")
DIODE = use("Device", "D")
TVS = use("Device", "D_TVS")
FUSE = use("Device", "Fuse")

FP_TBL = "board2:SameSky_TBL002A-350-08_1x08_P3.50mm_45deg"   # custom, from Same Sky TBL002A-350 datasheet
FP_J3 = "board2:SameSky_TBP02R1-381-16BE_1x16_P3.81mm_RA_PinsReversed"   # built from Same Sky datasheet TBP02R1-381 rev 1.04; pad numbers mirrored
FP_TB2 = "TerminalBlock_Phoenix:TerminalBlock_Phoenix_MKDS-1,5-2-5.08_1x02_P5.08mm_Horizontal"  # PLACEHOLDER J2 (jack type OPEN)
FP_TB4 = "TerminalBlock_Phoenix:TerminalBlock_Phoenix_MKDS-1,5-4-5.08_1x04_P5.08mm_Horizontal"  # PLACEHOLDER SW1/SW2 (part OPEN)
FP_D2 = "Diode_THT:D_DO-201AD_P12.70mm_Horizontal"
FP_D3 = "Diode_THT:D_DO-27_P12.70mm_Horizontal"
FP_F2 = "Fuse:Fuseholder_Cylinder-5x20mm_Schurter_0031_8201_Horizontal_Open"                # PLACEHOLDER (holder type OPEN)
FP_J4 = "Connector_Molex:Molex_Micro-Fit_3.0_43045-0412_2x02_P3.00mm_Vertical"

text("PCB2 / Board 2 - wire-operator board (no IC). Generated by gen_schematic.py from docs/board2-pcb2-summary.md", 4, 6, 2.5)
text("Nets are defined by labels at each pin. Same label = same net. NETnA and NETnB are tied (same net) by design.", 4, 9, 1.8)

# ---- power ----
text("POWER:  J2 -> D2 -> F2 -> SW1 -> V12S ;  V12S -> SW2 -> IGN ;  D3 TVS VF-GND (between F2 and SW1)", 4, 14)
place(C1x02, "J2", "12V DC in", FP_TB2, 8, 21, {"1": "VJ2", "2": "GND"}, "12 V DC input (jack type OPEN)")
place(DIODE, "D2", "SB540", FP_D2, 20, 21, {"2": "VJ2", "1": "VD"}, "Reverse-polarity Schottky 5A/40V; cathode (band) toward F2")
place(FUSE, "F2", "2 A", FP_F2, 30, 21, {"1": "VD", "2": "VF"}, "2 A fuse + holder (OPEN)")
place(C1x04, "SW1", "4-pin screw terminal", FP_TB4, 42, 21,
      {"1": "VF", "2": "V12S", "3": "V12S", "4": "GND"}, "4-pin screw terminal to off-board illuminated switch (general power)")
place(C1x04, "SW2", "4-pin screw terminal", FP_TB4, 62, 21,
      {"1": "V12S", "2": "IGN", "3": "IGN", "4": "GND"}, "4-pin screw terminal to off-board illuminated switch (shared 12V_IGN)")
place(TVS, "D3", "1.5KE24A", FP_D3, 84, 21, {"1": "VF", "2": "GND"}, "TVS 1500W 24V unidirectional, DO-27; cathode (band) to VF (F2 out / SW1 in); 1.0 mm leads, 1.3 mm holes")

# ---- J3 / J7 (fixed 1:1) ----
text("OBD2 INPUT (fixed 1:1):  J3 pin n  =  J7 pin n   (pin 5 = GND, pin 16 = V12S)", 4, 36)
def obd(n):
    return "GND" if n == 5 else ("V12S" if n == 16 else f"OBD{n}")
place(C1x16, "J3", "TBP02R1-381-16BE (16-pos 3.81)", FP_J3, 8, 52, {str(n): obd(n) for n in range(1, 17)}, "From Board 1 OBD2 pigtail (male plug)")
# J71/J72 are turned 180 deg on the board, so their pin numbers run right to left; the mapping is reversed so that J3 pin n lines up with the
# same left-to-right position on J7 (J3 pin 1 -> J71's leftmost pin, which is pin 8).
place(C1x08, "J71", "TBL002A-350-08GR-2OR", FP_TBL, 26, 48, {str(n): obd(9 - n) for n in range(1, 9)}, "J7 OBD pins 1-8, pin 8 leftmost")
place(C1x08, "J72", "TBL002A-350-08GR-2OR", FP_TBL, 26, 66, {str(n): obd(17 - n) for n in range(1, 9)}, "J7 OBD pins 9-16, pin 8 leftmost")

# ---- J6 landing ----
text("J6 PATCH LANDING:  wires from J7 patch in here; a/b of each net are tied", 56, 36)
place(C1x08, "J6", "TBL002A-350-08GR-2OR", FP_TBL, 64, 54,
      {"1": "NET1", "2": "NET2", "3": "NET3", "4": "NET4", "5": "NET1", "6": "NET2", "7": "NET3", "8": "NET4"},
      "Pins 1-4 = NET1a..NET4a, pins 5-8 = NET1b..NET4b (a/b of each net tied)")

# ---- J4 outputs: 2x4 grid; pins 1 BAT, 2 NET, 3 IGN, 4 GND ----
text("J4 OUTPUT HEADERS (Micro-Fit 2x2 vertical):  pin1 12V_BAT=V12S, pin2 NET, pin3 12V_IGN=IGN, pin4 GND", 4, 90)
for i in range(4):
    for r, row in enumerate("AB"):
        ref = f"J4{i + 1 + 4 * r}"
        place(C1x04, ref, "43045-0412", FP_J4, 10 + 24 * i, 96 + 12 * r,
              {"1": "V12S", "2": f"NET{i + 1}", "3": "IGN", "4": "GND"},
              f"Header NET{i + 1}{'ab'[r]}: 1=12V_BAT 2=NET{i + 1} 3=12V_IGN 4=GND")

libs = "\n".join(e for e, _ in PARTS.values())
sch = (f'(kicad_sch (version 20250114) (generator "gen_schematic.py") (generator_version "1.0")\n\t(uuid "{ROOT}")\n\t(paper "A3")\n'
       f'\t(lib_symbols\n{libs}\n\t)\n' + "\n".join(body) +
       f'\n\t(sheet_instances (path "/" (page "1")))\n)\n')
with open(os.path.join(HERE, "board2.kicad_sch"), "w", encoding="utf-8", newline="\n") as f:
    f.write(sch)
pro = {"meta": {"filename": "board2.kicad_pro", "version": 3}, "schematic": {"drawing": {}}, "board": {}, "net_settings": {"classes": [{"name": "Default"}]}}
with open(os.path.join(HERE, "board2.kicad_pro"), "w", encoding="utf-8", newline="\n") as f:
    json.dump(pro, f, indent=2)
print("wrote", len(body), "elements")
